let idioma = "pt";

// salvo > idioma do navegador (de* → alemão, pt* → português, resto → inglês) > português
function detectarIdioma(salvo) {
  if (IDIOMAS.includes(salvo)) return salvo;
  const nav = String((typeof navigator !== "undefined" && navigator.language) || "pt").toLowerCase();
  return nav.startsWith("de") ? "de" : nav.startsWith("pt") ? "pt" : "en";
}

function t(chave, vars) {
  const s = TEXTOS[idioma][chave] ?? TEXTOS.pt[chave] ?? chave;
  // números entram no formato do idioma (0,3 em vez de 0.3; 1.000 ou 1,000)
  const valor = (v) => (typeof v === "number" && Number.isFinite(v) ? v.toLocaleString(LOCAIS[idioma]) : v);
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? valor(vars[k]) : m)) : s;
}
const temTexto = (chave) => chave in TEXTOS.pt;
const ordinal = (i) => t("ordinal", { n: idioma === "en" ? ordinalEn(i + 1) : i + 1 });
function ordinalEn(n) {
  const resto = n % 100;
  if (resto >= 11 && resto <= 13) return n + "th";
  return n + (["th", "st", "nd", "rd"][n % 10] || "th");
}
// um valor que o JS quer mostrar e que muda de idioma junto com a página
const K = (k, v) => ({ k, v });

// Aplica o texto de um elemento marcado (e seus atributos).
function aplicarEm(el) {
  const vars = el.dataset.i18nVars ? JSON.parse(el.dataset.i18nVars) : undefined;
  if (el.dataset.i18n) el.textContent = t(el.dataset.i18n, vars);
  else if (el.dataset.i18nHtml) el.innerHTML = t(el.dataset.i18nHtml, vars);
  for (const a of ATRIBUTOS) {
    const k = el.getAttribute("data-i18n-" + a);
    if (k) el.setAttribute(a, t(k, vars));
  }
}
function marcar(el, chave, vars, html = false) {
  delete el.dataset.i18n; delete el.dataset.i18nHtml;
  el.dataset[html ? "i18nHtml" : "i18n"] = chave;
  if (vars) el.dataset.i18nVars = JSON.stringify(vars); else delete el.dataset.i18nVars;
  aplicarEm(el);
}
// texto simples ou K(chave, vars)
function escrever(el, valor) {
  if (valor && typeof valor === "object") { marcar(el, valor.k, valor.v); return; }
  delete el.dataset.i18n; delete el.dataset.i18nHtml; delete el.dataset.i18nVars;
  el.textContent = valor;
}

function definirIdioma(l) {
  idioma = IDIOMAS.includes(l) ? l : "pt";
  document.documentElement.lang = LANG_HTML[idioma];
  document.title = t("meta.titulo");
  document.querySelector('meta[name="description"]').content = t("meta.descricao");
  const sel = "[data-i18n],[data-i18n-html]," + ATRIBUTOS.map((a) => `[data-i18n-${a}]`).join(",");
  document.querySelectorAll(sel).forEach(aplicarEm);
  document.querySelectorAll("[data-idioma]").forEach((b) => {
    b.classList.toggle("on", b.dataset.idioma === idioma);
    b.setAttribute("aria-pressed", b.dataset.idioma === idioma);
  });
}
